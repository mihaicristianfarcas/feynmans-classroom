/* Indexes the server keeps for people and agents, generated from the files a moment after anything
 * changes. An agent reads a 2 KB index instead of opening a hundred files: that's where the savings
 * in tokens and calls come from. They're derived, so they're not versioned, and edits to them are
 * overwritten.
 *
 *   INDEX.md                  the map: counts, recent changes, where to look
 *   library/INDEX.md          every book: folder, pages, chapters, annotations
 *   library/<book>/README.md  a book's chapters (page ranges, text files) and its annotations by chapter
 *   notes/INDEX.md            every note: folder, tags, links out, backlinks
 *   concepts/INDEX.md         every concept: summary, mastery, cards, sources
 *   brain/links.tsv           every link: from, to, kind, line (backlinks are one rg away)
 *   brain/unresolved.tsv      links to things that don't exist yet */
import { join } from "node:path";
import { positionOf } from "../books/locate.ts";
import { bookFolder, listBooks, onBooksChange } from "../books/store.ts";
import type { Book, TocEntry } from "../books/types.ts";
import { conceptMastery } from "../learn/context.ts";
import {
  annotations,
  atomicWrite,
  cards,
  concepts,
  figures,
  notes,
  onVaultChange,
  VAULT,
  wroteItself,
} from "./index.ts";
import { chapterFile } from "./library.ts";
import { allEdges, invalidateLinks } from "./links.ts";

const HEADER = "<!-- Generated by Feynman's Classroom from the files in this vault. Edits here are overwritten. -->";
const cell = (s: unknown) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\s+/g, " ")
    .trim();
const day = (iso: string) => iso.slice(0, 16).replace("T", " ");
const pagesOf = (e: TocEntry, book: Book) =>
  book.format === "pdf"
    ? `${e.start.page ?? ""}–${Math.max(e.start.page ?? 1, (e.end.page ?? e.start.page ?? 1) - ((e.end.y ?? 1) <= 0.02 ? 1 : 0))}`
    : `blocks ${e.start.block ?? 0}–${e.end.block ?? ""}`;

function write(rel: string, text: string) {
  wroteItself(rel);
  atomicWrite(join(VAULT, rel), `${HEADER}\n${text.trim()}\n`);
}

/** The chapter at a reading position (before the first chapter counts as the first). */
const chapterOf = (book: Book, at: number) =>
  [...book.toc].reverse().find((c) => positionOf(c.start) <= at + 1e-6) || book.toc[0];

export function writeIndexes() {
  const books = listBooks().filter((b) => b.status === "ready");
  const edges = allEdges();
  const linksOut = new Map<string, number>();
  const linksIn = new Map<string, number>();
  for (const e of edges) {
    if (e.kind === "source" || e.kind === "mentions") continue;
    linksOut.set(e.from, (linksOut.get(e.from) || 0) + 1);
    if (e.to) linksIn.set(e.to, (linksIn.get(e.to) || 0) + 1);
  }

  /* each book */
  for (const book of books) {
    const folder = bookFolder(book.id);
    if (!folder) continue;
    const mine = annotations.list().filter((a) => a.bookId === book.id);
    const fromBook = notes.list().filter((n) => n.source?.bookId === book.id);
    const bookConcepts = concepts.list().filter((c) => c.sources.some((s) => s.bookId === book.id));
    const at = (a: (typeof mine)[number]) => positionOf(a.anchor);
    const lines = [
      `# ${book.title}`,
      "",
      `${book.author ? `by ${book.author} · ` : ""}${book.format === "pdf" ? `PDF, ${book.pageCount} pages` : `${book.format}, ${book.blockCount} blocks`} · added ${day(book.createdAt)} · file \`${book.file}\`${book.sha256 ? ` (sha256 ${book.sha256}…)` : ""} · book id \`${book.id}\``,
      "",
      "## Chapters",
      "",
      `| # | chapter | ${book.format === "pdf" ? "pages" : "where"} | text | annotations |`,
      "|---|---|---|---|---|",
      ...book.toc.map(
        (c, i) =>
          `| ${i + 1} | ${cell(c.title)}${c.subtitle ? ` — ${cell(c.subtitle)}` : ""} | ${pagesOf(c, book)} | [${chapterFile(book, i).split("/").slice(2).join("/")}](${chapterFile(book, i).split("/").slice(2).join("/")}) | ${mine.filter((a) => chapterOf(book, at(a))?.id === c.id).length || ""} |`,
      ),
    ];
    if (mine.length) {
      lines.push("", "## Annotations", "");
      for (const c of book.toc) {
        const here = mine.filter((a) => chapterOf(book, at(a))?.id === c.id).sort((a, b) => at(a) - at(b));
        if (!here.length) continue;
        lines.push(`### ${c.title}`, "");
        for (const a of here) {
          const where = a.anchor.page !== undefined ? `p. ${a.anchor.page}` : `block ${a.anchor.block}`;
          lines.push(
            `- ${where} · ${a.kind}${a.request ? ` (“${cell(a.request).slice(0, 80)}”)` : ""} · “${cell(a.anchor.quote).slice(0, 90)}…” → [[${a.path.replace(/\.md$/, "")}]]`,
          );
        }
        lines.push("");
      }
    }
    if (fromBook.length)
      lines.push(
        "",
        "## Notes from this book",
        "",
        ...fromBook.map((n) => `- [[${n.title}]]${n.type !== "note" ? ` (${n.type})` : ""}`),
      );
    if (bookConcepts.length)
      lines.push("", "## Concepts", "", ...bookConcepts.map((c) => `- [[${c.name}]] — ${cell(c.summary)}`));
    write(`library/${folder}/README.md`, lines.join("\n"));
  }

  /* the library */
  write(
    "library/INDEX.md",
    [
      "# Library",
      "",
      `${books.length} book${books.length === 1 ? "" : "s"}. Each folder holds book.json, the file, its text by chapter (text/), annotations/ and a README.md with the chapters and annotations.`,
      "",
      "| book | author | folder | format | size | chapters | annotations | added |",
      "|---|---|---|---|---|---|---|---|",
      ...books.map(
        (b) =>
          `| ${cell(b.title)} | ${cell(b.author)} | [${bookFolder(b.id)}/](${bookFolder(b.id)}/README.md) | ${b.format} | ${b.format === "pdf" ? `${b.pageCount} pages` : `${b.blockCount} blocks`} | ${b.toc.length} | ${annotations.list().filter((a) => a.bookId === b.id).length || ""} | ${b.createdAt.slice(0, 10)} |`,
      ),
    ].join("\n"),
  );

  /* notes */
  const noteList = notes.list().sort((a, b) => a.path.localeCompare(b.path));
  write(
    "notes/INDEX.md",
    [
      "# Notes",
      "",
      `${noteList.length} note${noteList.length === 1 ? "" : "s"}. The file name is the title. "out" and "in" count links (in: backlinks; see brain/links.tsv).`,
      "",
      "| note | folder | type | tags | out | in | updated |",
      "|---|---|---|---|---|---|---|",
      ...noteList.map(
        (n) =>
          `| [[${n.title}]] | ${cell(n.path.split("/").slice(1, -1).join("/"))} | ${n.type} | ${cell(n.tags.join(", "))} | ${linksOut.get(`note:${n.id}`) || ""} | ${linksIn.get(`note:${n.id}`) || ""} | ${day(n.updated)} |`,
      ),
    ].join("\n"),
  );

  /* concepts */
  const at = Date.now();
  const conceptList = concepts.list().sort((a, b) => a.name.localeCompare(b.name));
  write(
    "concepts/INDEX.md",
    [
      "# Concepts",
      "",
      `${conceptList.length} concept${conceptList.length === 1 ? "" : "s"}. Mastery is the predicted recall of the concept's cards right now (or the best explain-it-back score).`,
      "",
      "| concept | id | summary | mastery | cards | books | in |",
      "|---|---|---|---|---|---|---|",
      ...conceptList.map((c) => {
        const m = conceptMastery(c.id, at);
        return `| [[${c.name}]] | \`${c.id}\` | ${cell(c.summary).slice(0, 140)} | ${m === null ? "" : `${Math.round(m * 100)}%`} | ${cards.list().filter((k) => k.concepts.includes(c.id)).length || ""} | ${cell([...new Set(c.sources.map((s) => books.find((b) => b.id === s.bookId)?.title).filter(Boolean))].join(", "))} | ${linksIn.get(`concept:${c.id}`) || ""} |`;
      }),
    ].join("\n"),
  );

  /* links */
  const tsv = [
    "from\tto\tkind\tline",
    ...edges.filter((e) => e.to).map((e) => `${e.fromPath}\t${e.toPath || e.to}\t${e.kind}\t${e.line}`),
  ];
  wroteItself("brain/links.tsv");
  atomicWrite(join(VAULT, "brain/links.tsv"), `${tsv.join("\n")}\n`);
  const missing = [
    "from\ttarget\tline",
    ...edges.filter((e) => !e.to).map((e) => `${e.fromPath}\t${e.target}\t${e.line}`),
  ];
  wroteItself("brain/unresolved.tsv");
  atomicWrite(join(VAULT, "brain/unresolved.tsv"), `${missing.join("\n")}\n`);

  /* the map */
  const recent = [
    ...notes.list().map((n) => ({ path: n.path, when: n.updated })),
    ...concepts.list().map((c) => ({ path: concepts.fileOf(c.id) || "", when: c.updated })),
    ...annotations.list().map((a) => ({ path: a.path, when: a.updated })),
  ]
    .filter((x) => x.path)
    .sort((a, b) => b.when.localeCompare(a.when))
    .slice(0, 20);
  write(
    "INDEX.md",
    [
      "# Vault index",
      "",
      `Updated ${day(new Date().toISOString())} (UTC). Conventions are in AGENTS.md.`,
      "",
      "| what | how many | where |",
      "|---|---|---|",
      `| books | ${books.length} | [library/INDEX.md](library/INDEX.md), then library/<book>/README.md |`,
      `| notes | ${notes.items.size} | [notes/INDEX.md](notes/INDEX.md) |`,
      `| concepts | ${concepts.items.size} | [concepts/INDEX.md](concepts/INDEX.md) |`,
      `| annotations | ${annotations.items.size} | library/<book>/annotations/, listed in each book's README.md |`,
      `| flashcards | ${cards.items.size} | cards/ |`,
      `| saved figures | ${figures.items.size} | figures/ |`,
      `| links | ${edges.filter((e) => e.to).length} (${edges.filter((e) => !e.to).length} unresolved) | brain/links.tsv, brain/unresolved.tsv |`,
      "",
      "## Recently changed",
      "",
      ...recent.map((r) => `- ${day(r.when)} · ${r.path}`),
    ].join("\n"),
  );
}

let timer: ReturnType<typeof setTimeout> | null = null;
/** Rewrites the indexes a moment from now (changes come in bursts). */
export function scheduleIndexes(delay = 1500) {
  if (timer) clearTimeout(timer);
  timer = setTimeout(() => {
    timer = null;
    try {
      writeIndexes();
    } catch (error) {
      console.warn("[vault] could not write the indexes:", (error as Error).message);
    }
  }, delay);
}

export function startIndexing() {
  onBooksChange(() => {
    invalidateLinks();
    scheduleIndexes();
  });
  onVaultChange((rel) => {
    if (!rel.startsWith("brain/links") && !rel.startsWith("brain/unresolved")) scheduleIndexes();
  });
  scheduleIndexes(200);
}
